import subprocess
import tarfile
import tempfile

from consolidate import write_json
from .contracts import digest, require, inside


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def write_new(path,value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".record-",dir=path.parent) as tmp:
        candidate=Path(tmp)/"value.json";write_json(candidate,value);os.link(candidate,path)


def save_arrays(path,**values):
    import numpy as np
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".arrays-",dir=path.parent) as tmp:
        candidate=Path(tmp)/"values.npz"
        with candidate.open("xb") as stream:np.savez_compressed(stream,**values)
        os.link(candidate,path)


def extract_snapshot(archive,destination,expected):
    """Validate all entries before writing any file; never extract links/devices."""
    destination=Path(destination)
    with tarfile.open(archive,"r:gz") as source:
        members=source.getmembers();seen=set()
        for entry in members:
            name=PurePosixPath(entry.name)
            require(not name.is_absolute() and ".." not in name.parts and name.parts and name.parts[0]=="source", "Unsafe source snapshot entry")
            require(entry.isdir() or entry.isfile(), "Snapshot links/devices forbidden")
            if entry.isfile():
                require(0<=entry.size<=2*1024**2,"Oversized source snapshot entry")
                relative=PurePosixPath(*name.parts[1:]).as_posix()
                require(relative in expected and relative not in seen,"Unexpected snapshot source")
                seen.add(relative)
        require(seen==set(expected),"Snapshot source inventory incomplete")
        destination.mkdir(parents=True,exist_ok=False)
        for entry in members:
            if entry.isfile():
                relative=PurePosixPath(*PurePosixPath(entry.name).parts[1:]).as_posix()
                target=inside(destination,relative);target.parent.mkdir(parents=True,exist_ok=True)
                with source.extractfile(entry) as stream, target.open("xb") as output:output.write(stream.read())
                require(digest(target)==expected[relative],"Snapshot file hash mismatch")


def snapshot(root,work):
    from source_readiness import verify
    report=verify(root)
    archive=work/"source.tar.gz"
    names=subprocess.check_output(["git","ls-tree","-r","--name-only",report["git_commit"]],cwd=root,text=True).splitlines()
    hashes={p:digest(inside(root,p)) for p in names}
    subprocess.run(["git","archive","--format=tar.gz","--prefix=source/","--output="+str(archive),report["git_commit"]],cwd=root,check=True)
    extract_snapshot(archive,work/"source",hashes)
    return {"commit":report["git_commit"],"sha256":digest(archive),"files":hashes}


def verify_snapshot(work,record):
    require(digest(work/"source.tar.gz")==record["sha256"],"Source archive changed")
    for name,expected in record["files"].items():
        require(digest(inside(work/"source",name))==expected,"Snapshot source changed: "+name)
    # Only generated bytecode may appear in addition to the source inventory.
    for directory,dirs,files in os.walk(work/"source",followlinks=False):
        for name in dirs+files:
            require(not (Path(directory)/name).is_symlink(),"Symlink in source snapshot")
        for name in files:
            relative=(Path(directory)/name).relative_to(work/"source")
            require(relative.as_posix() in record["files"] or ("__pycache__" in relative.parts and relative.suffix==".pyc"),"Unexpected snapshot file")
